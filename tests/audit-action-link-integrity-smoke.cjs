'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const src=fs.readFileSync('audit-closed-loop-workflow.js','utf8');
const begin=src.indexOf('const linked=acts.filter(a=>a.sourceStage');
const end=src.indexOf('}if(acts.some(a=>String(a.id||',begin);
assert(begin>=0&&end>begin,'Audit action linkage guard not found');
const guard=src.slice(begin,end+1);
assert(guard.includes('linked.length>1'),'duplicate linkage must be rejected');
assert(guard.includes('first!==savedFirst'),'original auditor mismatch must be rejected');
const evaluate=new Function('acts','draw',guard+';return null;');
const draw={id:'AUD-1',initialAuditor:'first@hd.com'};
const valid={id:'ACT-1',sourceStage:'AUDIT-REQUEST',sourceCaseId:'AUD-1',auditDrawId:'AUD-1',initialAuditor:'first@hd.com'};
assert.equal(evaluate([valid],draw),'ACT-1','matching action must be reused');
assert.equal(evaluate([],draw),null,'new action may be created only without existing linkage');
assert.throws(()=>evaluate([valid,{...valid,id:'ACT-2'}],draw),/중복/,'duplicate action linkage must fail');
assert.throws(()=>evaluate([{...valid,initialAuditor:'other@hd.com'}],draw),/최초 점검자/,'auditor mismatch must fail');
assert.throws(()=>evaluate([{...valid,auditDrawId:'AUD-2'}],draw),/원본번호/,'source conflict must fail');
assert.equal(evaluate([{...valid,sourceStage:'OTHER'}],draw),null,'unrelated source must not be reused');
console.log('PASS: Audit action link deduplication and original-auditor identity');
